// Shared camera grammar (bridge short motion.md): symmetric smootherstep glides, cuts, dolly push + punch.
// Moved verbatim from the legacy timeline; the storyboard interpreter uses the same functions.
import type { Cam } from "../world";
import type { V3 } from "../places";
import { glide } from "./timing";

export type Shot = Partial<Cam> & { pos: V3; look: V3 };
export type Key = { f: number; dur?: number; cut?: boolean; s: (f: number) => Shot };

export const full = (c: Shot): Cam => ({ fov: 40, roll: 0, ...c });
export const mixC = (a: Cam, b: Cam, k: number): Cam => ({
  pos: a.pos.map((v, i) => v + (b.pos[i] - v) * k) as V3, look: a.look.map((v, i) => v + (b.look[i] - v) * k) as V3,
  fov: a.fov + (b.fov - a.fov) * k, roll: a.roll + (b.roll - a.roll) * k,
});
export const run = (keys: Key[]) => (f: number) => {
  let cur = full(keys[0].s(f));
  for (let i = 1; i < keys.length; i++) {
    const k = keys[i];
    if (f < k.f) break;
    cur = k.cut ? full(k.s(f)) : mixC(cur, full(k.s(f)), glide((f - k.f) / (k.dur ?? 24)));
  }
  return cur;
};
export const pushK = (f: number, f0: number, rate: number, punch = 0, n = 35) => {
  const x = Math.max(0, f - f0);
  let s = rate * x;
  if (punch > rate) for (let i = 0; i < Math.min(x, n); i++) s += (punch - rate) * Math.max(0, Math.min(1, (i + 0.5) / 8, (n - i - 0.5) / 8));
  return Math.exp(-s);
};
/** dolly push toward the look point from frame f0 */
export const dolly = (pos: V3, look: V3, f0: number, rate = 0.0025, rest: Partial<Cam> = {}, punch = 0, pf = -1) => (f: number): Shot => {
  const k = pushK(f, f0, rate) * (pf >= 0 ? pushK(f, pf, 0, punch, 30) : 1);
  return { pos: [look[0] + (pos[0] - look[0]) * k, look[1] + (pos[1] - look[1]) * k, look[2] + (pos[2] - look[2]) * k], look, ...rest };
};

export type Kick = [number, number];
export const kickAt = (f: number, kicks: Kick[]) => {
  let a = 0;
  for (const [f0, g] of kicks) { const n = f - f0; if (n >= 0 && n < 7) a += g * (n % 2 ? -1 : 1) * (1 - n / 7) ** 1.5; }
  return a;
};
export const kickCam = (f: number, c: Cam, kicks: Kick[]): Cam => {
  const a = kickAt(f, kicks);
  if (!a) return c;
  const d: V3 = [c.look[0] - c.pos[0], c.look[1] - c.pos[1], c.look[2] - c.pos[2]];
  const L = Math.hypot(...d), h = Math.hypot(d[0], d[2]) || 1;
  const m = (3 / 640) * Math.tan((c.fov * Math.PI) / 360) * L * a;
  return { ...c, look: [c.look[0] - (d[2] / h) * m, c.look[1] + 0.6 * m, c.look[2] + (d[0] / h) * m], roll: c.roll + a * 0.004 };
};
